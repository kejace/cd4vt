#!/usr/bin/env python3
"""Freeze the Comparator challenge from a trusted git revision.

Usage:  python3 comparator/prepare_challenge.py [REV]   (default: HEAD)

Copies, byte for byte from REV, the import closure of the modules that state
the theorems in config.json into comparator/Challenge/, under the module
prefix `Challenge.`.  Only internal `import Gluck.…` / `import ForMathlib.…`
lines are rewritten; declaration namespaces and proofs are unchanged, so the
challenge declares the same fully qualified theorem names as the solution.
Writes comparator/Challenge.lean (the root) and Challenge/REVISION.
Refuses to overwrite an existing snapshot; delete comparator/Challenge first.
"""
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
ROOTS = [
    "Gluck.Discrete.TabachnikovConverse",
    "Gluck.Discrete.TabachnikovCharacterization",
    "Gluck.Discrete.SideTangentConverse",
    "Gluck.Discrete.SideTangentForward",
    "Gluck.Discrete.LocalContinuity",
    "Gluck.Discrete.GlobalContinuity.EnclosingCircleObstruction",
]
PROJECT = ("Gluck", "ForMathlib")
IMPORT = re.compile(rb"^import\s+(\S+)", re.M)
PROJECT_IMPORT = re.compile(rb"^import\s+((?:Gluck|ForMathlib)(?:\.\S+)?)\s*$", re.M)


def git(*args: str) -> bytes:
    return subprocess.run(["git", "-C", str(REPO), *args], check=True,
                          stdout=subprocess.PIPE).stdout


def source(rev: str, module: str) -> bytes:
    return git("show", f"{rev}:{module.replace('.', '/')}.lean")


def main() -> int:
    rev = git("rev-parse", sys.argv[1] if len(sys.argv) > 1 else "HEAD").decode().strip()
    out = HERE / "Challenge"
    if out.exists():
        print(f"{out} exists; delete it to re-freeze", file=sys.stderr)
        return 1
    seen: set[str] = set()
    pending = list(ROOTS)
    while pending:
        module = pending.pop()
        if module in seen:
            continue
        seen.add(module)
        data = source(rev, module)
        for imp in IMPORT.findall(data):
            name = imp.decode()
            if name.split(".")[0] in PROJECT:
                pending.append(name)
        data = PROJECT_IMPORT.sub(rb"import Challenge.\1", data)
        dest = out / (module.replace(".", "/") + ".lean")
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)
    (out / "REVISION").write_text(rev + "\n")
    root = ["-- Generated by prepare_challenge.py; frozen at " + rev + "."]
    root += [f"import Challenge.{m}" for m in ROOTS]
    (HERE / "Challenge.lean").write_text("\n".join(root) + "\n")
    print(f"challenge: {len(seen)} modules frozen at {rev}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
